// ANSI 转义序列清理:终端输出里混有大量控制符(颜色、光标移动、括号粘贴模式等),
// 查看完整历史 / 导出 txt 时要先去掉这些,只留可读文本。
// 覆盖常见序列:
//  - CSI: \x1b[ ... —— 颜色/光标/[?2004h 括号粘贴/[K 清行等;
//    参数除 0-9;? 外还含 : < = >(如 [>4;1m 键盘协议、[<...M 鼠标 SGR);
//  - OSC: \x1b] ... (\x1b\\ 或 \x07 结尾) —— 标题/超链接;
//  - DCS/APC/PM/SOS: \x1bP / \x1b_ / \x1b^ / \x1bX ...(以 \x1b\\ 结束) —— 六色/粘贴板等;
//  - 单字符 ESC 序列: \x1b[()? ...
//  - 响铃 \x07、单独残留的 ESC \x1b、孤立的回车 \r(不属于 \r\n)
export function stripAnsi(text: string): string {
  return (text || '')
    // 数字/分号/参数分隔(:;<==>) + 中间字节(空格~/)+ 终结字节
    .replace(/\x1b\[[0-9;:<=>?]*[ -\/]*[@-~]/g, '')
    // OSC: \x1b] ... 以 ST(\x1b\\)
    .replace(/\x1b\][^\x1b]*(?:\x1b\\)?/g, '')
    // OSC 以 BEL 结尾的另一种形式
    .replace(/\x1b\][^\x07\x1b]*\x07/g, '')
    // DCS/APC/PM/SOS/ST: \x1b[P_^X\\] ... 到 \x1b\\
    .replace(/\x1b[P_^X\\][^\x1b]*(?:\x1b\\)?/g, '')
    // 字符集选择等短序列 \x1b(0 / \x1b)B 等
    .replace(/\x1b[()][0-9A-Z]/g, '')
    // 响铃
    .replace(/\x07/g, '')
    // \r(回车)保留:完整历史 / 导出会用 \r 作为换行分隔。全屏 TUI(如 codeagent/htop)
    // 常以 \r 原地刷新而不换行,若在此删掉 \r,整屏输出会被压成一行导致"内容看不到"。
    // 清理任何残留的单字节 ESC 控制符(防御性)
    .replace(/\x1b/g, '')
}
